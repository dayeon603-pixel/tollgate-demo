/**
 * Receipt network, demo edition: how a payment that arrives with the sender's signed receipt is
 * accepted without a second screening, and how it is refused when the receipt cannot be relied on.
 *
 * Real: every key is a fresh Ed25519 key made in this browser, every receipt and share is signed
 * with it, and verifyShare checks them offline with Web Crypto. Synthetic: the member institutions
 * ("Demo Exchange A, B, C"), their payments and the clock. Field names and rules follow the
 * shared-receipt registration in the research repo (docs/PREREG_SHARED_RECEIPTS.md, branch
 * feat/network): format "tollgate-share" version 1, a decision receipt D and a signed
 * "network_share" receipt S, a skeleton digest over the issuer's earlier receipts, single use, and
 * a 24 hour freshness limit. Differences, stated: the demo ships no list file in the share (it
 * names the list by digest, which the receiving side already holds), and no share is sealed, so
 * every acceptance reads "issuer's word only".
 *
 * Nothing here decides whether an address is sanctioned. The receiving side's own list always wins.
 */
import { canon } from '../verifier.js';
import { sha256Hex } from '../workbench.js';
import { bytesToHex, checkReceipt, hexToBytes, listSnapshotOf } from './receipt-check.js';

export const SHARE_FORMAT = 'tollgate-share';
export const SHARE_VERSION = 1;
export const FRESHNESS_MS = 24 * 3_600_000;
export const FUTURE_SKEW_MS = 300_000;
export const MAX_SHARE_CHARS = 200_000;
export const MEMBER_AGENT = 'tollgate.demo-member';
export const GENESIS = '0'.repeat(64);
export const BASIS_WORDS = { issuer_word: "ACCEPTED UNDER YOUR POLICY, ISSUER'S WORD ONLY", seal: 'ACCEPTED UNDER YOUR POLICY, SEALED' };

/** Why a share was refused, as a short label and a sentence. The first reason found is the headline. */
export const REASONS = {
  format: ['Unreadable', 'The share is not in the tollgate-share format, version 1.'],
  bad_signature: ['Bad signature', 'The receipt was changed after it was signed, or its signature does not match.'],
  wrong_signer: ['Signer mismatch', 'The receipt and the share statement were not signed by the key the sender named.'],
  chain_position: ['Chain position', "The receipt's place in the sender's chain does not match what the sender signed."],
  subject_mismatch: ['Statement mismatch', "The sender's signed share statement disagrees with the receipt it covers."],
  unknown_key: ['Unknown key', 'The signing key is not in your registry.'],
  not_pinned: ['Key not pinned', 'The key is in your registry but you have not pinned it, so you do not rely on it yet.'],
  key_revoked: ['Key revoked', 'You revoked this key. An unsealed receipt from a revoked key is refused whatever time it claims.'],
  expired: ['Too old', 'The decision is older than your freshness limit, or the sender\'s own expiry has passed.'],
  future: ['Dated in the future', 'The receipt claims a time later than your clock allows.'],
  stale_list: ['Stale list', 'The receipt was made on an older list version than the one you hold now.'],
  list_ahead: ['List not held', 'The receipt was made on a newer list version than the one you hold. Apply your list update first.'],
  list_unknown: ['Unknown list', 'The receipt names a list you do not hold, so it cannot be re-checked.'],
  on_own_list: ['On your own list', 'The address is on your own list. Your list wins whatever the sender says.'],
  wrong_scope: ['Different payment', 'The receipt covers a different address, chain or counterparty than this payment.'],
  not_clear: ['Not a clear', 'Only a screening decision that allowed the payment can be relied on.'],
  reused: ['Already used', 'This share was already relied on once. A share is used once.'],
  no_receipt: ['No receipt', 'The sender sent no receipt, so the payment is screened here.'],
};

export const reasonLabel = (code) => REASONS[code]?.[0] ?? code;
export const reasonText = (code) => REASONS[code]?.[1] ?? code;

const lower = (s) => String(s ?? '').toLowerCase();

// ---- keys ---------------------------------------------------------------------------------

/**
 * Makes a new member: a fresh Ed25519 key pair generated by Web Crypto in this browser.
 * Returns: { name, keyId (public key, hex), jwk (private key, for this browser's storage only), privateKey }.
 */
export async function generateInstitution(name) {
  const pair = await crypto.subtle.generateKey({ name: 'Ed25519' }, true, ['sign', 'verify']);
  return {
    name, keyId: bytesToHex(await crypto.subtle.exportKey('raw', pair.publicKey)),
    jwk: await crypto.subtle.exportKey('jwk', pair.privateKey), privateKey: pair.privateKey,
  };
}

/** Rebuilds a member from the stored private JWK. Raises when the stored key is unusable. */
export async function restoreInstitution({ name, keyId, jwk }) {
  const privateKey = await crypto.subtle.importKey('jwk', jwk, { name: 'Ed25519' }, false, ['sign']);
  return { name, keyId, jwk, privateKey };
}

// ---- the sending side -----------------------------------------------------------------------

/** A demo member that screens payments and shares its receipts. Its chain starts empty each session. */
export class DemoMember {
  constructor({ name, keyId, privateKey }) {
    this.name = name;
    this.keyId = keyId;
    this.privateKey = privateKey;
    this.chain = [];
    this.slug = `m${keyId.slice(0, 4)}`;
  }

  async #sign(type, params, decision, reasons, ts, listDigest) {
    const seq = this.chain.length;
    const prevHash = seq ? this.chain[seq - 1].this_hash : GENESIS;
    const id = `${this.slug}-${seq + 1}`;
    const iso = ts.toISOString();
    const action = { action_id: `act:${id}`, agent_id: MEMBER_AGENT, mandate_id: `rulebook:SDN-OFAC-${listDigest.slice(0, 12)}`, type, params, requested_at: iso };
    const unsigned = {
      verdict_id: `vd:${id}`, action_id: action.action_id, authorizer_id: this.keyId, decision, reasons, decided_at: iso,
      action_digest: await sha256Hex(canon(action)),
    };
    const signature = bytesToHex(await crypto.subtle.sign({ name: 'Ed25519' }, this.privateKey, new TextEncoder().encode(canon(unsigned))));
    const verdict = { ...unsigned, signature };
    const receipt = { receipt_id: `rcpt:${id}`, seq, prev_hash: prevHash, action, verdict, this_hash: '' };
    receipt.this_hash = await sha256Hex(canon({ seq, prev_hash: prevHash, action, verdict }));
    this.chain.push(receipt);
    return receipt;
  }

  /**
   * Screens one payment and shares the receipt.
   *
   * Args: spec { address, chain, counterparty, amountUsd, outcome ('ALLOW' | 'BLOCK'), listDigest, listLabel, ts (Date) }.
   * Returns: a share object (format tollgate-share, version 1).
   */
  async makeShare({ address, chain, counterparty = null, amountUsd, outcome = 'ALLOW', listDigest, listLabel, ts }) {
    const paymentId = `P-${ts.getTime().toString(36)}-${this.chain.length + 1}`;
    const params = {
      payment_id: paymentId, outcome, beneficiary_address: address, chain, counterparty_address: counterparty,
      amount_usd: amountUsd, list_version: listLabel, source: 'member_screening', synthetic: true,
    };
    const rulebook = `SDN-OFAC-${listDigest.slice(0, 12)}`;
    const reasons = [`outcome=${outcome}`, `rulebook_version=${rulebook}`, `list_snapshot=${listDigest}`, outcome === 'ALLOW' ? 'clean' : 'sanctions_hit=demo'];
    const decision = await this.#sign('stablecoin_payment_screen', params, outcome === 'ALLOW' ? 'ALLOW' : 'DENY', reasons, ts, listDigest);
    const earlier = this.chain.slice(0, -1).map((r) => ({ seq: r.seq, prev_hash: r.prev_hash, this_hash: r.this_hash }));
    const seqPlusHash = this.chain.slice(0, -1).map((r) => [r.seq, r.this_hash]);
    const shareId = `shr:${(await sha256Hex(`${decision.this_hash}|${this.chain.length}`)).slice(0, 16)}`;
    const subject = {
      receipt_id: decision.receipt_id, seq: decision.seq, this_hash: decision.this_hash, outcome, beneficiary_address: address, chain,
      counterparty_address: counterparty, decided_at: ts.toISOString(), list_version: listLabel, list_snapshot: listDigest,
    };
    const statement = {
      share_id: shareId, share_format: SHARE_FORMAT, subject, single_use: true, expires_at: new Date(ts.getTime() + FRESHNESS_MS).toISOString(),
      skeleton_digest: await sha256Hex(canon([...seqPlusHash, [decision.seq, decision.this_hash]])), issuer_name: this.name, actor: 'issuer',
    };
    const share = await this.#sign('network_share', statement, 'RECORD', [`outcome=SHARED`, `rulebook_version=${rulebook}`, `list_snapshot=${listDigest}`, `share_id=${shareId}`], new Date(ts.getTime() + 1000), listDigest);
    const withheld = earlier;
    return {
      format: SHARE_FORMAT, version: SHARE_VERSION, share_id: shareId, issuer: { key_id: this.keyId, name: this.name },
      bundle: { receipts: [decision, share], withheld }, list_file: null, seal: null,
    };
  }
}

/** Deep copy, so a test or the "edited after signing" scenario can change a share without touching the original. */
export const cloneShare = (share) => JSON.parse(JSON.stringify(share));

// ---- the receiving side ---------------------------------------------------------------------

/**
 * Checks a share the way the receiving side would, offline. Every check runs and every failure is
 * reported; the first one in rule order is the headline.
 *
 * Args: share (untrusted); env { now (Date), registry (Map keyId -> { status: 'registered' | 'pinned' | 'revoked' }),
 *   listDigest (the list in force), versions ([{ id, label, digest, ordinal }]), inForceOrdinal,
 *   ownListHas(address) -> boolean, used (Set of share ids already relied on), want { address, chain, counterparty },
 *   freshnessMs }.
 * Returns: { accepted, reasons: [{ code, label, text }], headline, basis, facts }.
 */
export async function verifyShare(share, env) {
  const reasons = [];
  const flag = (code, extra = '') => { if (!reasons.some((r) => r.code === code)) reasons.push({ code, label: reasonLabel(code), text: `${reasonText(code)}${extra ? ` ${extra}` : ''}` }); };
  const done = (facts = null) => ({ accepted: reasons.length === 0, reasons, headline: reasons[0] ?? null, basis: 'issuer_word', facts });

  // 1. Format
  const text = (() => { try { return JSON.stringify(share); } catch { return null; } })();
  const [d, s] = share?.bundle?.receipts ?? [];
  if (!text || text.length > MAX_SHARE_CHARS || share.format !== SHARE_FORMAT || share.version !== SHARE_VERSION || !d || !s
    || share.bundle.receipts.length !== 2 || !Array.isArray(share.bundle.withheld) || d.action?.type !== 'stablecoin_payment_screen'
    || s.action?.type !== 'network_share' || typeof share.issuer?.key_id !== 'string') {
    flag('format');
    return done();
  }
  const keyId = share.issuer.key_id;
  const dp = d.action.params ?? {};
  const sp = s.action.params ?? {};
  const facts = {
    shareId: sp.share_id ?? share.share_id, keyId, issuerName: share.issuer.name, receiptId: d.receipt_id, receiptHash: d.this_hash,
    address: dp.beneficiary_address, chain: dp.chain, counterparty: dp.counterparty_address ?? null, amountUsd: dp.amount_usd ?? null,
    decidedAt: d.verdict?.decided_at, outcome: dp.outcome, listDigest: listSnapshotOf(d), listLabel: dp.list_version,
  };

  // 2. Integrity: both receipts, one key, the chain skeleton, and a statement that agrees with the receipt.
  for (const receipt of [d, s]) {
    const check = await checkReceipt(receipt, { expectKey: keyId });
    if (!check.ok) flag(check.code === 'signer' ? 'wrong_signer' : 'bad_signature', `(${receipt.receipt_id})`);
  }
  if (share.share_id !== sp.share_id) flag('subject_mismatch');
  const subject = sp.subject ?? {};
  if (subject.this_hash !== d.this_hash || subject.beneficiary_address !== dp.beneficiary_address || subject.outcome !== dp.outcome
    || subject.list_snapshot !== facts.listDigest || subject.decided_at !== d.verdict?.decided_at || subject.chain !== dp.chain
    || (subject.counterparty_address ?? null) !== (dp.counterparty_address ?? null)) flag('subject_mismatch');
  const withheld = share.bundle.withheld;
  const bySeq = new Map(withheld.map((w) => [w.seq, w]));
  bySeq.set(d.seq, { seq: d.seq, prev_hash: d.prev_hash, this_hash: d.this_hash });
  const skeleton = [];
  let contiguous = Number.isInteger(s.seq) && s.seq === d.seq + 1;
  for (let i = 0; i < s.seq && contiguous; i++) {
    const w = bySeq.get(i);
    if (!w) { contiguous = false; break; }
    const before = i === 0 ? GENESIS : bySeq.get(i - 1)?.this_hash;
    if (w.prev_hash !== before) contiguous = false;
    skeleton.push([i, w.this_hash]);
  }
  if (!contiguous || s.prev_hash !== d.this_hash || (await sha256Hex(canon(skeleton))) !== sp.skeleton_digest) flag('chain_position');

  // 3. Issuer known and trusted. 5. Revocation.
  const member = env.registry.get(keyId);
  if (!member) flag('unknown_key');
  else if (member.status === 'revoked') flag('key_revoked');
  else if (member.status !== 'pinned') flag('not_pinned');

  // 6. Freshness.
  const decided = Date.parse(d.verdict?.decided_at);
  const age = env.now.getTime() - decided;
  if (Number.isNaN(decided) || age < -FUTURE_SKEW_MS) flag('future');
  else if (age > (env.freshnessMs ?? FRESHNESS_MS) || Date.parse(sp.expires_at) < env.now.getTime()) flag('expired');

  // 7. List: the receipt must be made on the list this side holds now.
  if (facts.listDigest !== env.listDigest) {
    const made = env.versions.find((v) => v.digest === facts.listDigest);
    if (!made) flag('list_unknown');
    else if (made.ordinal < env.inForceOrdinal) flag('stale_list', `(${made.label}, you hold ${env.versions.find((v) => v.ordinal === env.inForceOrdinal).label}).`);
    else flag('list_ahead', `(${made.label}).`);
  }

  // 8. Our own list wins.
  if (env.ownListHas(dp.beneficiary_address) || (dp.counterparty_address && env.ownListHas(dp.counterparty_address))) flag('on_own_list');

  // 9. Scope.
  const want = env.want ?? {};
  if ((want.address && lower(want.address) !== lower(dp.beneficiary_address)) || (want.chain && lower(want.chain) !== lower(dp.chain))
    || (want.counterparty !== undefined && lower(want.counterparty ?? '') !== lower(dp.counterparty_address ?? ''))) flag('wrong_scope');

  // 10. Clear only.
  if (dp.outcome !== 'ALLOW' || d.verdict?.decision !== 'ALLOW') flag('not_clear');

  // 11. Single use.
  if (env.used.has(facts.shareId)) flag('reused');
  return done(facts);
}

